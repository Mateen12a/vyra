const { test, expect } = require('@playwright/test');
const path = require('node:path');
test('uploaded video and logo render in the local editor', async ({ page }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/watermark');
  await page.locator('#upload').setInputFiles(path.resolve('.data/browser-fixtures/source.mp4'));
  await expect(page.locator('#record')).toBeEnabled();
  await page.locator('#logo').setInputFiles(path.resolve('.data/browser-fixtures/reference.png'));
  await page.locator('#position').selectOption('center');
  await expect.poll(() => page.evaluate(() => document.querySelector('#output').width)).toBeLessThan(1281);
  await expect.poll(() => page.evaluate(() => document.querySelector('#source').readyState)).toBeGreaterThan(1);
  await page.waitForTimeout(500);
  expect(errors).toEqual([]);
});
test('watermark webcam draws, repairs selected region, and exports recording', async ({ page }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/watermark');
  await page.getByRole('button', { name: 'Start camera' }).click();
  await expect(page.locator('#record')).toBeEnabled();
  await page.locator('#text').fill('TEST LOGO');
  const box = await page.locator('#output').boundingBox();
  await page.mouse.move(box.x + box.width * .1, box.y + box.height * .1);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .25, box.y + box.height * .2);
  await page.mouse.up();
  await page.locator('#remove').check();
  await page.getByRole('button', { name: 'Record output', exact: true }).click();
  await expect(page.locator('#record')).toHaveText('Stop recording');
  await page.waitForTimeout(3000);
  await page.getByRole('button', { name: 'Stop recording' }).click();
  await expect(page.locator('#download')).toBeVisible();
  const waiting = page.waitForEvent('download');
  await page.locator('#download').click();
  const download = await waiting;
  expect(download.suggestedFilename()).toBe('vyrani-watermark.webm');
  const file = await download.path();
  expect(require('node:fs').statSync(file).size).toBeGreaterThan(1000);
  expect(errors).toEqual([]);
});
